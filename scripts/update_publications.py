#!/usr/bin/env python3
"""Regenerate the publication lists in publications.md from a .bib file.

Only the text between the BEGIN/END markers in publications.md is replaced.

Usage:
    python3 scripts/update_publications.py [--bib my_publications.bib]
                                           [--page publications.md] [--check]
"""
import argparse
import re
import sys
from pathlib import Path

BEGIN = "<!-- BEGIN BIB PUBLICATIONS (generated by scripts/update_publications.py; do not edit) -->"
END = "<!-- END BIB PUBLICATIONS -->"
ME = ("la tona", "g")  # (lowercase last name, first initial) to bold

SECTIONS = [
    ("Journal Articles", {"article"}),
    ("Conference Papers", {"inproceedings", "inbook", "incollection", "conference", "proceedings"}),
    ("Preprints", set()),
    ("Technical Reports", {"techreport", "tech", "report", "misc"}),
]
PREPRINT_VENUES = ("techrxiv", "arxiv", "preprints.org", "ssrn", "researchsquare")
PARTICLES = {"di", "de", "da", "del", "la", "lo", "van", "von"}


def parse_bib(text):
    entries, pos = [], 0
    head = re.compile(r"@(\w+)\s*\{\s*([^,\s]*)\s*,")
    while True:
        m = head.search(text, pos)
        if not m:
            break
        i, depth = m.end(), 1
        while i < len(text) and depth:
            depth += {"{": 1, "}": -1}.get(text[i], 0)
            i += 1
        body, pos = text[m.end():i - 1], i
        kind = m.group(1).lower()
        if kind not in ("comment", "string", "preamble"):
            entries.append({"type": kind, "key": m.group(2), **parse_fields(body)})
    return entries


def parse_fields(body):
    fields, i, n = {}, 0, len(body)
    field = re.compile(r"\s*,?\s*([\w-]+)\s*=\s*")
    while i < n:
        m = field.match(body, i)
        if not m:
            break
        name, i = m.group(1).lower(), m.end()
        if i < n and body[i] == "{":
            depth, j = 1, i + 1
            while j < n and depth:
                depth += {"{": 1, "}": -1}.get(body[j], 0)
                j += 1
            value, i = body[i + 1:j - 1], j
        elif i < n and body[i] == '"':
            j = body.index('"', i + 1)
            value, i = body[i + 1:j], j + 1
        else:
            m2 = re.compile(r"[^,]*").match(body, i)
            value, i = m2.group(0).strip(), m2.end()
        fields[name] = clean(value)
    return fields


def clean(s):
    s = re.sub(r"\s+", " ", s).strip()
    s = s.replace("\\&", "&").replace("--", "–")
    return re.sub(r"[{}]", "", s)


def initials(first):
    out = []
    for p in (p for p in re.split(r"[\s.]+", first) if p):
        if "-" in p:
            out.append("-".join(q[0].upper() + "." for q in p.split("-") if q))
        elif p.isupper() and len(p) <= 3:  # "MC" -> M. C.
            out.extend(c + "." for c in p)
        else:
            out.append(p[0].upper() + ".")
    return " ".join(out)


def split_name(name):
    if "," in name:
        last, first = (x.strip() for x in name.split(",", 1))
        return last, first
    words = name.split()
    if len(words) == 1:
        return name, ""
    k = len(words) - 1
    while k > 1 and words[k - 1].lower() in PARTICLES:
        k -= 1
    return " ".join(words[k:]), " ".join(words[:k])


def format_authors(raw):
    out = []
    for n in (n.strip() for n in re.split(r"\s+and\s+", raw)):
        if not n:
            continue
        last, first = split_name(n)
        txt = f"{last}, {initials(first)}" if first else last
        if last.lower() == ME[0] and first[:1].lower() == ME[1]:
            txt = f"**{txt}**"
        out.append(txt)
    if len(out) > 1:
        return ", ".join(out[:-1]) + ", & " + out[-1]
    return out[0] if out else ""


def is_preprint(e):
    venue = (e.get("journal") or e.get("howpublished") or "").lower()
    return e["type"] == "preprint" or any(v in venue for v in PREPRINT_VENUES)


def section_of(e):
    if is_preprint(e):
        return "Preprints"
    for name, types in SECTIONS:
        if e["type"] in types:
            return name
    return None


def format_entry(e):
    parts = [f"{format_authors(e.get('author', ''))} ({e.get('year', 'n.d.')}). {e['title'].rstrip('.')}."]
    pages = e.get("pages")
    if e.get("journal"):
        s = f"*{e['journal']}*"
        vol, issue = e.get("volume"), e.get("issue") or e.get("number")
        loc = []
        if vol and not is_preprint(e):
            loc.append(vol + (f"({issue})" if issue else ""))
        if pages:
            loc.append(pages)
        parts.append(s + (", " + ", ".join(loc) if loc else "") + ".")
    elif e.get("booktitle"):
        parts.append(f"In *{e['booktitle']}*" + (f" (pp. {pages})" if pages else "") + ".")
    elif e.get("institution"):
        parts.append(", ".join(x for x in (e["institution"], e.get("city")) if x) + ".")
    if e.get("publisher") and not e.get("journal"):
        parts.append(f"{e['publisher']}.")
    line = " ".join(parts)
    if e.get("doi"):
        line += f" [DOI: {e['doi']}](https://doi.org/{e['doi']})"
    elif e.get("url"):
        line += f" [Link]({e['url']})"
    return "- " + line


def month_num(e):
    m = e.get("month", "").strip().lower()
    names = ["jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"]
    if m[:3] in names:
        return names.index(m[:3]) + 1
    return int(m) if m.isdigit() else 0


def norm_title(e):
    return re.sub(r"\W+", "", e.get("title", "").lower())


def build(entries):
    published = {norm_title(e) for e in entries if not is_preprint(e)}
    seen, kept = set(), []
    for e in entries:
        if section_of(e) is None or not e.get("title"):
            continue
        sig = (norm_title(e), e.get("year"))
        # Drop exact duplicates and preprints whose published version is listed.
        if sig in seen or (is_preprint(e) and norm_title(e) in published):
            continue
        seen.add(sig)
        kept.append(e)

    out = []
    for name, _ in SECTIONS:
        items = [e for e in kept if section_of(e) == name]
        if not items:
            continue
        out.append(f"## {name}\n")
        for y in sorted({e.get("year", "n.d.") for e in items}, reverse=True):
            group = sorted((e for e in items if e.get("year", "n.d.") == y), key=month_num, reverse=True)
            out.append(f"### {y}")
            out.append("\n\n".join(format_entry(e) for e in group) + "\n")
        out.append("---\n")
    return "\n".join(out).rstrip("\n") + "\n", len(kept)


def main():
    root = Path(__file__).resolve().parent.parent
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--bib", default=root / "my_publications.bib", type=Path)
    ap.add_argument("--page", default=root / "publications.md", type=Path)
    ap.add_argument("--check", action="store_true", help="exit 1 if the page is out of date")
    args = ap.parse_args()

    body, count = build(parse_bib(args.bib.read_text(encoding="utf-8")))
    page = args.page.read_text(encoding="utf-8")
    if BEGIN not in page or END not in page:
        sys.exit(f"Markers not found in {args.page}")
    new = re.sub(
        re.escape(BEGIN) + r".*?" + re.escape(END),
        lambda _: f"{BEGIN}\n\n{body}\n{END}",
        page,
        flags=re.S,
    )
    if args.check:
        sys.exit(0 if new == page else 1)
    args.page.write_text(new, encoding="utf-8")
    print(f"Wrote {count} publications to {args.page}")


if __name__ == "__main__":
    main()
